def write_file(path: Path, content: str, force: bool) -> str:
    if path.exists() and not force:
        return f"skip existing {path}"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return f"wrote {path}"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--project-root", default=".", help="Target project root")
    parser.add_argument("--plan-path", default="doc/browser-walkthrough-plan.md")
    parser.add_argument("--script-path", default="scripts/browser-walkthrough.mjs")
    parser.add_argument("--force", action="store_true", help="Overwrite existing files")
    args = parser.parse_args()

    root = Path(args.project_root).resolve()
    results = [
        write_file(root / args.plan_path, PLAN_TEMPLATE, args.force),
        write_file(root / args.script_path, RUNNER_TEMPLATE, args.force),
    ]
    (root / "doc" / "browser-walkthrough-reports").mkdir(parents=True, exist_ok=True)
    for line in results:
        print(line)
    print(f"ensured {root / 'doc' / 'browser-walkthrough-reports'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
